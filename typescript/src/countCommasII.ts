function countCommas(n: number): number {
    if(n < 1000) {
        return 0;
    } else if( n >= 1000 && n < 1000000){
        //1000 - 545200
        return n - 1000 + 1;
    } else if(n >= 1000000 && n < 1000000000){
        // 1000 - 245,540,023
        return ((n - 1000 + 1) * 2) - 1000000 + 1000;
    }else if(n >= 1000000000 && n < 1000000000000){
        return ((n - 1000 + 1) * 3) - 1000000000 - 1000000 + 2000;
    } else if(n >= 1000000000000 && n < 1000000000000000){
        return ((n - 1000 + 1) * 4) - 1000000000000 - 1000000000 - 1000000 + 3000;
    }
    
    return ((n - 1000 + 1) * 5) - 1000000000000000 - 1000000000000 - 1000000000 - 1000000 + 4000;
};

